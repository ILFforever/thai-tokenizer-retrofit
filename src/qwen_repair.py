"""Can Qwen2.5's 1,578 dead Thai rows be repaired cheaply?

    python src/qwen_repair.py                                   # full run, CPU
    python src/qwen_repair.py --docs 3 --quick 2 --steps 4 --eval-every 2 \\
        --english 3 --no-write                                  # smoke test

Writes results/qwen_repair.json and the repair tables inside
results/QWEN_UNREACHABLE.md (between their own markers, so re-running either
script keeps the other's output).

Why. `qwen_unreachable.py` showed that every Thai vocabulary entry Qwen2.5's
shipped pre-tokenizer cannot emit has an untrained embedding row - all 1,578
sit on the padding vector - and that switching to the mark-aware regex
without retraining makes Thai bits per character 2-3x worse. The damage is
confined to those rows, so the question is whether fixing only them brings
the model back while keeping the ~35% token saving. Two steps, each scored
with the mark-aware tokenizer on exactly the Test 2 passages and protocol:

  mean       Fast Vocabulary Transfer (Gee et al. 2022): each dead row
             becomes the mean of the rows of the tokens the *shipped*
             tokenizer splits its string into. No training.
  mean+tune  then train only those rows on Thai training text (documents
             after the evaluation slice, equal characters per domain),
             tokenized with the mark-aware tokenizer. Every other weight is
             frozen. Embeddings are tied, so the same rows learn both how to
             be read and how to be predicted.

English bits per character is checked at each step: a tied row competes in
the output softmax at every position, English included, so a repair that
makes Thai rows too attractive would show up there first.

Cost: the trainable rows live in their own (1,578 x 896) parameter, so the
dense gradient of the 151,936-row output head is never formed; the rest of
the model is compared bit-for-bit with the checkpoint afterwards.
"""

